/**
 * The helper module that makes Icarus record a waveform without touching the student's
 * files (docs/waveform_viewer_spec.md § 7.3): compiled as a second root beside the
 * student's top (`-s <top> -s hdlboard_wave`), it dumps the whole design from the top
 * down. The file name comes in as a plusarg, so one compile serves every start of the
 * run – a Reset writes a new file while the stopped process may still hold the old one.
 * Pure.
 */

export const WAVE_MODULE_NAME = 'hdlboard_wave';
export const WAVE_MODULE_FILE_NAME = 'hdlboard_wave.v';
/** `+hdlboard_wave=<file>` on `vvp`'s command line. */
export const WAVE_PLUSARG = 'hdlboard_wave';
/** Room for the file name in the module's string register, in characters. */
const FILE_NAME_CHARACTERS = 64;

export function waveModuleSource(top: string): string {
  return [
    `// Generated by HDLBoard: records the waveform of ${top} (docs/waveform_viewer_spec.md).`,
    `module ${WAVE_MODULE_NAME};`,
    `  reg [8*${FILE_NAME_CHARACTERS}-1:0] file_name;`,
    '  initial begin',
    `    if (!$value$plusargs("${WAVE_PLUSARG}=%s", file_name)) file_name = "wave.vcd";`,
    '    $dumpfile(file_name);',
    `    $dumpvars(0, ${top});`,
    '  end',
    'endmodule',
    '',
  ].join('\n');
}

/** The plusarg that names this start's file. */
export const wavePlusarg = (fileName: string): string => `+${WAVE_PLUSARG}=${fileName}`;
